const keys = Object.keys(english).sort((a, b) => b.length - a.length);
const pattern = new RegExp(
  keys.map((k) => k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'),
  'g',
);
export function translateText(text: string, locale: Locale = 'en'): string {
  if (locale === 'zh-CN') return text;
  if (english[text] !== undefined) return english[text];
  // Translate longest phrases once, preserving inserted English and arbitrary IDs/numbers.
  return text.replace(pattern, (match) => english[match]);
}
